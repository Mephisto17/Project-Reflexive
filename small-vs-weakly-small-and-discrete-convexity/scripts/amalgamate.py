#!/usr/bin/env python3
"""Generate the standalone source from the project's import dependency graph."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
seen, modules, external = set(), [], []

def visit(name):
    if name in seen:
        return
    seen.add(name)
    path = ROOT / (name.replace('.', '/') + '.lean')
    if not path.is_file():
        if not name.startswith('Mathlib.'):
            raise RuntimeError(f'Unexpected external import: {name}')
        external.append(name)
        return
    text = path.read_text()
    for dependency in re.findall(r'^import\s+(\S+)\s*$', text, re.M):
        visit(dependency)
    modules.append((name, text))

visit('TalagrandIntegral')
header = '''/-
Small-vs-Weakly-Small-and-Talagrand-Discrete-Convexty-Conjecture

Lean verification of Talagrand's small-versus-weakly-small conjecture
and discrete-convexity conjecture, from the two uploaded papers:
  Integral and fractional expectation thresholds are equivalent.
  Talagrand's discrete-convexity conjecture.

Lean 4.32.0; mathlib 81a5d257c8e410db227a6665ed08f64fea08e997.
Generated by scripts/amalgamate.py. See README.md for scope and proof route.
No project-local imports are required by this standalone file.
-/
'''
parts = [header, '\n'.join('import ' + name for name in external), '\n']
for name, text in modules:
    body = re.sub(r'^import\s+\S+\s*\n', '', text, flags=re.M)
    # Each original module starts with Lean's default options. Preserve that
    # default for the inherited fractional-certificate modules.
    implicit = 'true' if name.startswith('TalagrandConjectures.') else 'false'
    parts += [f'\n/- ===== {name} ===== -/\n',
              f'set_option autoImplicit {implicit}\n', body]
out = ROOT / 'Small-vs-Weakly-Small-and-Talagrand-Discrete-Convexty-Conjecture.lean'
out.write_text('\n'.join(parts))
print(f'{out.name}: {len(modules)} local modules; {len(out.read_text().splitlines())} lines')
